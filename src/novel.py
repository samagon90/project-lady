def validate_scenario(scenario: dict[str, dict]) -> list[str]:
    """Проверяет целостность сценария: все переходы существуют,
    есть хотя бы одна концовка, у каждого узла есть картинка."""
    errors: list[str] = []
    for node_id, node in scenario.items():
        if not node.get("image"):
            errors.append(f"{node_id}: нет image")
        choices = node.get("choices") or []
        if not choices:
            errors.append(f"{node_id}: нет вариантов")
        for _text, next_id in choices:
            if next_id not in scenario:
                errors.append(f"{node_id}: переход '{next_id}' не существует")
    if not any(n.get("ending") for n in scenario.values()):
        errors.append("нет ни одной концовки")
    return errors
